#!/usr/bin/env python3
"""Which curves are alike, which are alone, and where the set is thin.

    .venv/bin/python scripts/similar_curves.py            # print the report
    .venv/bin/python scripts/similar_curves.py --write    # write state/SIMILARITY-int.md

Reads `workbench/curve-analysis.json` (written by `scripts/analyse_curves.ts`).
No database: this is analysis of a file, so it can run anywhere.

The distance is over the numbers that describe a curve's shape rather than its
name: crossing pairs, inflection count, median curvature, bend, the three
symmetry gaps, grid and degree. Each is scaled to a common spread first, so a
grid of 86,625,000,000 does not drown a symmetry gap of 0.02.

Two things come out of it:

- **neighbours** — for each curve, the three nearest others, with the distance;
- **thin regions** — curves whose nearest neighbour is far away. Those are the
  places the set has not explored, which is where to search next.

The gaps table is the search target: a cell of (crossings, inflections, symmetry)
with few curves in it is a place a new family would land somewhere new.
"""

from __future__ import annotations

import argparse
import json
import math
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FILE = ROOT / "workbench" / "curve-analysis.json"
OUT = ROOT / "state" / "SIMILARITY-int.md"

FEATURES = ("crossings", "inflections", "curvatureMedian", "bend",
            "mirrorY", "halfTurn", "mirrorYX", "grid", "degree")


def vector(row):
    values = []
    for key in FEATURES:
        value = row.get(key)
        value = float(value) if isinstance(value, (int, float)) else 0.0
        if key in ("curvatureMedian", "bend", "grid"):
            value = math.log1p(max(value, 0.0))
        values.append(value)
    return values


def scaled(rows):
    columns = list(zip(*(vector(row) for row in rows)))
    scales = []
    for column in columns:
        spread = statistics.pstdev(column)
        scales.append(spread or 1.0)
    return [tuple(value / scales[i] for i, value in enumerate(vector(row))) for row in rows]


def distance(a, b):
    return math.sqrt(sum((x - y) ** 2 for x, y in zip(a, b)))


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--neighbours", type=int, default=3)
    args = parser.parse_args(argv)

    data = json.loads(FILE.read_text(encoding="utf-8"))
    rows = [row for row in data["curves"] if row.get("kind") != "error"]
    vectors = scaled(rows)
    k = args.neighbours

    pairs = []
    for i in range(len(rows)):
        for j in range(i + 1, len(rows)):
            pairs.append((distance(vectors[i], vectors[j]), i, j))

    nearest = [[] for _ in rows]
    for d, i, j in sorted(pairs):
        if len(nearest[i]) < k:
            nearest[i].append((d, j))
        if len(nearest[j]) < k:
            nearest[j].append((d, i))

    for i, row in enumerate(rows):
        row["neighbours"] = [(round(d, 3), rows[j]["name"]) for d, j in nearest[i]]
        row["loneliness"] = round(nearest[i][0][0], 3) if nearest[i] else 0.0

    alone = sorted(rows, key=lambda row: -row["loneliness"])[:15]

    # The gaps: crossings x inflections, and how many curves sit in each cell.
    cells = {}
    for row in rows:
        key = (min(row.get("crossings") or 0, 12), min(row.get("inflections") or 0, 8))
        cells.setdefault(key, []).append(row)
    wanted = [(c, f) for c in range(0, 13) for f in range(0, 9)]
    empty = [cell for cell in wanted if not cells.get(cell)]
    thin = sorted(((len(v), k2) for k2, v in cells.items()))[:10]

    print(f"{len(rows)} curves · {len(pairs)} pairs")
    print("closest pair:", min(pairs)[0].__round__(3))
    print("loneliest:", ", ".join(f"{row['name']} ({row['loneliness']})" for row in alone[:5]))
    print(f"empty (crossings, inflections) cells: {len(empty)} of {len(wanted)}")
    if empty:
        print("  examples:", ", ".join(str(cell) for cell in empty[:8]))

    if not args.write:
        return 0

    lines = [
        "# SIMILARITY-int — what the numbers say about the curves",
        "",
        "Generated by `scripts/similar_curves.py --write` from "
        "`workbench/curve-analysis.json`. Do not edit by hand.",
        "",
        f"{len(rows)} curves compared on crossings, inflections, median curvature, bend,",
        "the three symmetry gaps, grid and degree. Each scaled to a common spread.",
        "",
        "## The loneliest curves — the shapes nothing else is like",
        "",
        "| curve | nearest neighbour | distance |",
        "|---|---|---|",
    ]
    for row in alone:
        lines.append(f"| {row['name']} | {row['neighbours'][0][1] if row['neighbours'] else '—'} | {row['loneliness']} |")
    lines += [
        "",
        "## Thin cells — (crossing pairs, inflections) with few curves",
        "",
        "A cell with no curve is a shape the set has never tried. That is the",
        "search list, not a fault.",
        "",
        "| crossings | inflections | curves | example |",
        "|---|---|---|---|",
    ]
    for count, (c, f) in thin:
        example = cells[(c, f)][0]["name"]
        lines.append(f"| {c} | {f} | {count} | {example} |")
    lines += [
        "",
        f"Empty cells: **{len(empty)}** of {len(wanted)}.",
        "",
        "## Neighbours, for every curve",
        "",
        "| curve | 1st | 2nd | 3rd |",
        "|---|---|---|---|",
    ]
    for row in rows:
        names = " | ".join(f"{name} ({d})" for d, name in row["neighbours"][:3])
        lines.append(f"| {row['name']} | {names} |")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
