"""Build `llms-full.txt`: the project's own documents in one plain file.

    .venv/bin/python scripts/llms_full.py           # write
    .venv/bin/python scripts/llms_full.py --check   # exit 1 if stale

`llms.txt` is the short index an agent reads first. This file is the long form:
the same documents, concatenated with their paths, so one request is enough to
understand the engine, the rules and the current state.

Add a document here when it is one an agent should read before editing code.
Do not add generated HTML, images, or anything under archive/.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "llms-full.txt"

DOCUMENTS = [
    "README.md",
    "llms.txt",
    "AGENTS.md",
    "senior-dev.md",
    "docs/index.md",
    "docs/WORKED-EXAMPLE.md",
    "docs/STATE-OF-THE-WORK.md",
    "docs/PROJECT.md",
    "docs/STRUCTURE.md",
    "docs/ARCHITECTURE.md",
    "docs/GLOSSARY.md",
    "docs/CURVE-MODEL.md",
    "docs/PH-INTEGER.md",
    "docs/VERIFY.md",
    "docs/FIDELITY.md",
    "docs/CLEARANCE.md",
    "docs/JUNCTION.md",
    "docs/PHILOSOPHY.md",
    "docs/PRIMAL.md",
    "state/DESIGN-int.md",
    "state/REGRESSIONS-int.md",
    "state/DATA-int.md",
    "state/PORT-int.md",
    "app/README.md",
    "book/README.md",
]

HEAD = """# curve-lab — full text

> Exact integer and rational curves for ornament, with a Python engine, a
> browser lab and an Astro app. This file is generated by
> `scripts/llms_full.py`; edit the sources, not this copy.

Each document below is separated by a line giving its repository path. Paths are
relative to the repository root.

"""


def build() -> str:
    parts = [HEAD]
    for name in DOCUMENTS:
        path = ROOT / name
        text = path.read_text(encoding="utf-8").strip()
        parts.append(f"\n\n<!-- source: {name} -->\n\n{text}\n")
    return "".join(parts)


def main(argv: list[str]) -> int:
    expected = build()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != expected:
            print("stale: run .venv/bin/python scripts/llms_full.py")
            return 1
        print(f"{OUT.name} is current ({len(expected)} bytes, {len(DOCUMENTS)} documents)")
        return 0
    OUT.write_text(expected, encoding="utf-8")
    print(f"wrote {OUT.name} ({len(expected)} bytes, {len(DOCUMENTS)} documents)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
