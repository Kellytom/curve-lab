"""The stack page is true: its version table matches the installed packages.

`app/src/content/docs/docs/stack.md` is generated by `scripts/stack_doc.mjs`.
A hand-typed version goes stale; this test fails when the doc and the packages
disagree, which is the fault it prevents.
"""

import shutil
import subprocess
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# The project's Node is the tarball at ~/node24; a system node is often older
# and would make the table look stale.
NODE = Path.home() / "node24" / "bin" / "node"
if not NODE.exists():
    NODE = Path(shutil.which("node") or "node")


class StackDocTest(unittest.TestCase):
    def test_the_stack_doc_matches_the_installed_versions(self):
        result = subprocess.run(
            [NODE, "scripts/stack_doc.mjs", "--check"],
            cwd=ROOT, capture_output=True, text=True)
        self.assertEqual(0, result.returncode, result.stdout + result.stderr)


if __name__ == "__main__":
    unittest.main()
