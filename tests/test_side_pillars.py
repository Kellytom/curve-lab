"""Guards the side-pillar page: generated, labelled, thin, and in the hub.

The geometry rules themselves are in `tests/js/side-pillars.test.js` (the maths
is one implementation, `workbench/side_pillars.js`). This file guards the page:
that it is generated by the script, that it carries the words and units the
spec asks for, that its controls exist, and that the hub knows the page.
"""

import json
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / "workbench" / "side-pillars.html"
MATH = ROOT / "workbench" / "side_pillars.js"
MANIFEST = ROOT / "workbench" / "manifest.json"


class SidePillarPageTest(unittest.TestCase):
    def setUp(self):
        self.page = PAGE.read_text(encoding="utf-8")
        self.math = MATH.read_text(encoding="utf-8")

    def test_the_generator_reproduces_the_page(self):
        out = subprocess.run(
            [sys.executable, str(ROOT / "scripts" / "side_pillars.py")],
            capture_output=True, text=True, check=True,
        )
        self.assertTrue(out.stdout.strip().endswith("side-pillars.html"))
        self.assertEqual(self.page, PAGE.read_text(encoding="utf-8"))

    def test_the_page_carries_no_maths(self):
        # one script loads the maths, the second is the one-line mount
        self.assertIn('<script src="side_pillars.js"></script>', self.page)
        self.assertIn("<script>SidePillars.mount(document);</script>", self.page)
        self.assertEqual(self.page.count("<script"), 2)
        self.assertNotIn("function", self.page)

    def test_the_six_controls_and_their_readouts(self):
        for name in ("diameters", "ratio", "swell", "station", "base", "capital"):
            self.assertIn(f'id="sp-{name}"', self.page)
            self.assertIn(f'id="sp-{name}-val"', self.page)
        self.assertEqual(self.page.count('type="range"'), 6)

    def test_the_sliders_start_where_the_maths_starts(self):
        # register 42: a first paint from one value and a redraw from another is
        # two pictures for one page
        import re
        sys.path.insert(0, str(ROOT / "scripts"))
        import side_pillars as S
        d = S.defaults()
        for name, value in d["d"].items():
            found = re.search(rf'id="sp-{name}" type="range" min="[\d]+" max="[\d]+" value="(\d+)"', self.page)
            self.assertIsNotNone(found, name)
            self.assertEqual(int(found.group(1)), value, name)

    def test_the_figure_is_named_inside_the_figure(self):
        self.assertIn("Fig. P1 — the side pillar", self.math)
        for word in ("foot", "top", "swell", "base", "capital", "x", "y"):
            self.assertIn(word, self.math)

    def test_the_readout_names_its_units(self):
        for phrase in ("share of the height", "share of the foot", "in foot widths"):
            self.assertIn(phrase, self.math)
        # no percentage where a share of a stated reference will do
        self.assertNotIn("percent", self.math.lower())
        self.assertNotIn("% of", self.math)

    def test_the_legend_is_readable_at_full_width(self):
        self.assertIn("font:15px", self.page)
        for word in ("the pillar, one line", "glue-connected run", "model axes",
                     "straight taper the shaft swells against"):
            self.assertIn(word, self.page)

    def test_the_page_explains_the_object_before_the_numbers(self):
        for phrase in ("outside edge only", "quadratic", "entasis", "diameters tall"):
            self.assertIn(phrase, self.page)
        # the numbers table comes after the figure's explanation heading order
        self.assertLess(self.page.index("The numbers"), self.page.index("What the figure is"))

    def test_the_first_paint_is_the_same_maths_as_the_redraw(self):
        # the server's first paint and the browser's redraw come from one file
        sys.path.insert(0, str(ROOT / "scripts"))
        import side_pillars as S
        first = S.default_svg()
        self.assertIn(first, self.page)
        self.assertIn('id="sp-figure"', self.page)
        # the hub takes the page's first drawing as the thumbnail
        hub = (ROOT / "workbench" / "workbench.html").read_text(encoding="utf-8")
        self.assertIn("side-pillars.html", hub)

    def test_the_first_paint_puts_each_line_on_its_own_side(self):
        # the right line lives near x = +150, the left near x = -150; a control
        # point at the centre draws one bow across the whole page
        import re
        paths = re.findall(r'<path class="pillar" d="([^"]+)"', self.page)
        self.assertEqual(len(paths), 2)
        for d in paths:
            xs = [float(a) for a, _ in re.findall(r'(-?\d+(?:\.\d+)?) (-?\d+(?:\.\d+)?)', d)]
            sign = 1 if sum(xs) > 0 else -1
            for x in xs:
                self.assertGreater(sign * x, 140.0, d)
                self.assertLess(sign * x, 170.0, d)

    def test_the_hub_knows_the_page(self):
        manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
        rows = [p for p in manifest["pages"] if p["file"] == "side-pillars.html"]
        self.assertEqual(len(rows), 1)
        row = rows[0]
        self.assertEqual(row["group"], "curve")
        for key in ("title", "purpose", "inputs", "outputs"):
            self.assertTrue(row[key].strip(), key)


if __name__ == "__main__":
    unittest.main()
